    /// T-008 acceptance: start engine, mutate doc, shut down, restart,
    /// mutations are still present AND were broadcast to a peer engine
    /// during the first run.
    #[tokio::test]
    async fn engine_persists_and_broadcasts_mutations() {
        let (relay_map, relay_url, _relay_guard) =
            iroh::test_utils::run_relay_server().await.unwrap();
        let memory_lookup = MemoryLookup::new();

        let tmp = TempDir::new().unwrap();
        let store_a = store_in(&tmp, "a");
        let store_b = store_in(&tmp, "b");

        let body = async {
            // -- bring up two endpoints + cross-register addresses --------
            let ep_a = build_test_endpoint(relay_map.clone()).await;
            let ep_b = build_test_endpoint(relay_map.clone()).await;
            ep_a.address_lookup().unwrap().add(memory_lookup.clone());
            ep_b.address_lookup().unwrap().add(memory_lookup.clone());
            ep_a.online().await;
            ep_b.online().await;
            let id_a = ep_a.id();
            let id_b = ep_b.id();
            memory_lookup
                .add_endpoint_info(EndpointAddr::new(id_a).with_relay_url(relay_url.clone()));
            memory_lookup
                .add_endpoint_info(EndpointAddr::new(id_b).with_relay_url(relay_url.clone()));

            // -- bring up two transports on the same shared secret -------
            let secret = b"engine-test-shared-secret-aabb";
            let transport_a =
                Arc::new(Transport::start_with_endpoint(ep_a, secret, vec![]).await.unwrap());
            let transport_b =
                Arc::new(Transport::start_with_endpoint(ep_b, secret, vec![id_a]).await.unwrap());

            // -- bring up engine A (the one we'll mutate, then restart) --
            let doc_a = Arc::new(SyncDoc::from_doc(store_a.load().unwrap()));
            let engine_a = SyncEngine::start_with_parts(
                store_a.clone(),
                doc_a.clone(),
                transport_a.clone(),
                Bridge::new(doc_a.clone()),
            )
            .await
            .unwrap();

            // -- bring up engine B (the receiver) ------------------------
            let doc_b = Arc::new(SyncDoc::from_doc(store_b.load().unwrap()));
            let engine_b = SyncEngine::start_with_parts(
                store_b.clone(),
                doc_b.clone(),
                transport_b.clone(),
                Bridge::new(doc_b.clone()),
            )
            .await
            .unwrap();

            // Wait for the gossip mesh to form before mutating; otherwise
            // the broadcast can race ahead of the join and B never sees it.
            let mut rx_a = transport_a.subscribe();
            let mut rx_b = transport_b.subscribe();
            let join = async {
                let mut a_joined = false;
                let mut b_joined = false;
                while !(a_joined && b_joined) {
                    tokio::select! {
                        ev = rx_a.recv(), if !a_joined => {
                            if let Ok(TransportEvent::PeerConnected(_)) = ev { a_joined = true; }
                        }
                        ev = rx_b.recv(), if !b_joined => {
                            if let Ok(TransportEvent::PeerConnected(_)) = ev { b_joined = true; }
                        }
                    }
                }
            };
            timeout(Duration::from_secs(15), join)
                .await
                .expect("peers did not join in time");

            // -- mutate on A and assert it propagates to B ---------------
            doc_a.set_pref_display_name("Alice").unwrap();
            doc_a
                .set_course_overlay(
                    "12345",
                    crate::p2p::doc::CourseField::IsPinned(true),
                )
                .unwrap();

            let observed = timeout(Duration::from_secs(5), async {
                loop {
                    if doc_b.get_pref_display_name().as_deref() == Some("Alice")
                        && doc_b
                            .get_course_overlay("12345")
                            .and_then(|c| c.is_pinned)
                            == Some(true)
                    {
                        return ();
                    }
                    tokio::time::sleep(Duration::from_millis(50)).await;
                }
            })
            .await;
            assert!(observed.is_ok(), "engine B did not receive A's mutations within 5s");

            // -- shut down A; force its checkpoint -----------------------
            engine_a.shutdown().await.unwrap();
            engine_b.shutdown().await.unwrap();
            drop(engine_a);
            drop(engine_b);
            // Drop transports too so the next iteration can rebind.
            drop(transport_a);
            drop(transport_b);
            drop(doc_a);
            drop(doc_b);
        };

        timeout(Duration::from_secs(45), body)
            .await
            .expect("engine integration test exceeded 45s");

        // -- restart engine A from the same on-disk store ----------------
        // The transport doesn't matter for this assertion — we're proving
        // the WAL/snapshot survived, which is purely a SyncStore concern.
        let reloaded = SyncDoc::from_doc(store_a.load().unwrap());
        assert_eq!(reloaded.get_pref_display_name().as_deref(), Some("Alice"));
        assert_eq!(
            reloaded.get_course_overlay("12345").and_then(|c| c.is_pinned),
            Some(true),
        );
    }

