/// Periodic checkpoint cadence (design.md §9): the engine rewrites the
/// snapshot at most every `CHECKPOINT_INTERVAL`, and also opportunistically
/// when WAL entries exceed `CHECKPOINT_WAL_THRESHOLD`.
const CHECKPOINT_INTERVAL: Duration = Duration::from_secs(60);

/// Snapshot size that triggers a `p2p:warning` event on the
/// receiving Tauri app (T-022). Design.md §14 calls 50 MB out as
/// the soft limit before compaction becomes a real concern. The
/// warning is edge-triggered so the user doesn't see a toast every
/// minute once they're over.
const SNAPSHOT_WARNING_BYTES: u64 = 50 * 1_000_000;

pub struct SyncEngine {
    doc: Arc<SyncDoc>,
    store: Arc<SyncStore>,
    transport: Arc<Transport>,
    bridge: Arc<Bridge>,
    endpoint_id: EndpointId,

    cancel: CancellationToken,
    // Holding the loro Subscription keeps the local-update callback
    // registered; dropping the engine drops the subscription.
    _local_sub: loro::Subscription,
    _local_pump: AbortOnDropHandle<()>,
    _inbox_task: AbortOnDropHandle<()>,
    _checkpoint_task: AbortOnDropHandle<()>,
}

impl SyncEngine {
    /// Production entry point. Loads secrets from `app_state`, opens the
    /// on-disk SyncStore under `app_data_dir()/sync/`, brings up the
    /// transport, and spawns all background tasks.
    pub async fn start(state: Arc<AppState>) -> Result<Arc<Self>> {
        Self::start_with_bootstrap(state, Vec::new()).await
    }

    /// Like [`start`] but seeds the gossip transport with peers to
    /// dial proactively. Used by the QR-pairing joiner so it doesn't
    /// have to wait for relay-broadcast discovery before it can send
    /// `WireMsg::PairingRequest` to the seed.
    pub async fn start_with_bootstrap(
        state: Arc<AppState>,
        bootstrap_peers: Vec<EndpointId>,
    ) -> Result<Arc<Self>> {
        let (node_secret, doc_secret) = load_or_init_secrets(&state.pool).await?;

        let store = Arc::new(SyncStore::open(&state.app)?);
        let doc = Arc::new(SyncDoc::from_doc(store.load()?));
        let transport = Arc::new(
            Transport::start_with_bootstrap(node_secret, &doc_secret, bootstrap_peers).await?,
        );
        // Production wiring: Bridge::with_sql installs the Loro→SQLite
        // subscription so remote diffs land in the local DB and emit
        // matching Tauri events (T-010). The wrapping Arc<EventBus>
        // satisfies the BridgeEventSink trait object the bridge holds.
        let events: Arc<dyn crate::p2p::bridge::BridgeEventSink> =
            Arc::new(state.events.clone());
        let bridge = Bridge::with_sql(doc.clone(), state.pool.clone(), events);
        // Inject the live Brightspace client so the joiner-side of
        // BootstrapCredentials can call `store_credentials` directly.
        bridge.set_client(state.client.clone());

        Self::start_with_parts(store, doc, transport, bridge).await
    }

    /// Joiner-side QR-pairing entry point (T-013). Persists the
    /// `sync_doc_secret` carried in the QR, brings up the engine
    /// dialing the seed proactively, and broadcasts
    /// `WireMsg::PairingRequest { nonce }`. The seed verifies the
    /// nonce hasn't been consumed and replies with a `Snapshot`.
    ///
    /// The caller is expected to:
    ///   1. validate the QR via `pairing::consume_payload(&pool,
    ///      encoded)` first (rejects expired / replayed locally), then
    ///   2. call this with the resulting `PairingPayload`,
    ///   3. await the initial snapshot via
    ///      `engine.await_initial_snapshot(timeout).await?`,
    ///   4. run `engine.bridge().hydrate_from_doc().await?` to seed
    ///      SQLite from the freshly-imported Loro doc.
    ///
    /// The Tauri command `p2p_consume_pairing` (T-014) sequences all
    /// four steps so the React UI sees one async call.
    pub async fn pair_via_payload(
        state: Arc<AppState>,
        payload: &crate::p2p::pairing::PairingPayload,
    ) -> Result<Arc<Self>> {
        // Persist the shared secret BEFORE the engine starts so
        // load_or_init_secrets picks up this value rather than
        // generating a new random one. Goes through the same backend
        // (keychain primary, app_state fallback) so a re-pair lands
        // in the same place future loads will read from.
        crate::p2p::secrets::store(
            &state.pool,
            crate::p2p::secrets::SecretKind::SyncDocSecret,
            &payload.secret,
        )
        .await?;

        let seed: EndpointId = payload
            .node
            .parse()
            .map_err(|e| AppError::BadRequest(format!("pairing payload node id: {e}")))?;
        let engine = Self::start_with_bootstrap(state, vec![seed]).await?;

        // Send the pairing request now. Gossip won't have a neighbor
        // yet — the broadcast queues into the iroh send buffer and
        // ships once the dial completes (typically <1s in practice).
        engine
            .transport
            .broadcast(WireMsg::PairingRequest {
                nonce: payload.nonce.clone(),
            })
            .await?;

        Ok(engine)
    }

    /// Block until the first inbound `WireMsg::Snapshot` arrives, or
    /// `timeout` elapses. Used by the joiner after `pair_via_payload`
    /// to know it's safe to call `bridge.hydrate_from_doc()` — the
    /// hydration walk is meaningful only once the seed's snapshot has
    /// been imported.
    pub async fn await_initial_snapshot(&self, timeout: Duration) -> Result<()> {
        let mut rx = self.transport.subscribe();
        let waited = tokio::time::timeout(timeout, async {
            loop {
                match rx.recv().await {
                    Ok(TransportEvent::Message {
                        payload: WireMsg::Snapshot { .. },
                        ..
                    }) => return Ok::<(), AppError>(()),
                    Ok(_) => continue,
                    Err(broadcast::error::RecvError::Lagged(_)) => continue,
                    Err(broadcast::error::RecvError::Closed) => {
                        return Err(AppError::Other("transport inbox closed".into()));
                    }
                }
            }
        })
        .await;
        match waited {
            Ok(inner) => inner,
            Err(_) => Err(AppError::Other(format!(
                "no snapshot from seed within {}s",
                timeout.as_secs()
            ))),
        }
    }

    /// Test hook: caller has already built the parts (typically via the
    /// in-memory iroh test relay). Exposes the same task wiring as
    /// `start` without touching SQLite or `app_data_dir`.
    #[doc(hidden)]
    pub async fn start_with_parts(
        store: Arc<SyncStore>,
        doc: Arc<SyncDoc>,
        transport: Arc<Transport>,
        bridge: Arc<Bridge>,
    ) -> Result<Arc<Self>> {
        let endpoint_id = transport.endpoint_id();
        let cancel = CancellationToken::new();
        let checkpoint_notify = Arc::new(Notify::new());

        // -- local-update pump ---------------------------------------------
        // The Loro callback runs synchronously on the commit thread, so we
        // shovel each update onto an unbounded mpsc and let an async task
        // do the WAL write + broadcast. Unbounded is fine: commits are
        // user-paced (~1 per setter call), the consumer drains immediately,
        // and unbounded avoids any chance of blocking the commit hot path.
        let (local_tx, mut local_rx) = mpsc::unbounded_channel::<Vec<u8>>();
        let local_sub = doc.doc().subscribe_local_update(Box::new(move |bytes| {
            // send returns Err only if the receiver task has dropped,
            // which means the engine is shutting down — nothing to do.
            let _ = local_tx.send(bytes.clone());
            true
        }));

        let local_pump = AbortOnDropHandle::new(tokio::spawn({
            let store = store.clone();
            let transport = transport.clone();
            let cancel = cancel.clone();
            let notify = checkpoint_notify.clone();
            async move {
                loop {
                    let bytes = tokio::select! {
                        biased;
                        _ = cancel.cancelled() => break,
                        maybe = local_rx.recv() => match maybe {
                            Some(b) => b,
                            None => break,
                        },
                    };

                    if let Err(e) = store.append_update(&bytes) {
                        error!("wal append failed: {e}");
                    }
                    if store.pending_wal_entries() >= CHECKPOINT_WAL_THRESHOLD {
                        notify.notify_one();
                    }
                    if let Err(e) = transport
                        .broadcast(WireMsg::Update { bytes })
                        .await
                    {
                        // Broadcast failure is non-fatal — peers will resync
                        // via state-request when they reconnect.
                        warn!("local update broadcast failed: {e}");
                    }
                }
            }
        }));

        // -- inbox handler -------------------------------------------------
        let inbox_task = AbortOnDropHandle::new(tokio::spawn({
            let mut rx = transport.subscribe();
            let doc = doc.clone();
            let transport = transport.clone();
            let cancel = cancel.clone();
            // Pool is needed for the seed-side PairingRequest path
            // (consume_nonce against `consumed_pairing_nonces`). Tests
            // built via `Bridge::new` get None and skip nonce checks —
            // the gate is meaningful only when there's a real DB.
            let pool = bridge.pool().cloned();
            // Client is needed for the joiner-side BootstrapCredentials
            // path. Same story: tests skip, production has one.
            let client = bridge.client();
            async move {
                loop {
                    tokio::select! {
                        biased;
                        _ = cancel.cancelled() => break,
                        ev = rx.recv() => match ev {
                            Ok(TransportEvent::Message { from, payload }) => {
                                handle_inbound(
                                    &doc,
                                    &transport,
                                    pool.as_ref(),
                                    client.as_ref(),
                                    &from,
                                    payload,
                                )
                                .await;
                            }
                            Ok(TransportEvent::PeerConnected(id)) => {
                                info!("peer connected: {id}");
                            }
                            Ok(TransportEvent::PeerDisconnected(id)) => {
                                info!("peer disconnected: {id}");
                            }
                            Err(broadcast::error::RecvError::Lagged(n)) => {
                                warn!("inbox lagged {n} messages — state-sync will recover");
                            }
                            Err(broadcast::error::RecvError::Closed) => break,
                        }
                    }
                }
            }
        }));

        // -- checkpoint scheduler ------------------------------------------
        let checkpoint_task = AbortOnDropHandle::new(tokio::spawn({
            let store = store.clone();
            let doc = doc.clone();
            let cancel = cancel.clone();
            let notify = checkpoint_notify.clone();
            // Clone the events sink so we can emit p2p:warning when
            // the snapshot crosses 50 MB (T-022). None for tests
            // built via Bridge::new, which is fine — production has
            // a real EventBus and only production cares about UI
            // notifications anyway.
            let events = bridge.events().cloned();
            async move {
                let mut tick = interval(CHECKPOINT_INTERVAL);
                // Consume the immediate first tick so we don't checkpoint
                // an empty WAL the moment we boot.
                tick.tick().await;
                // Edge-triggered warning: only fire on the transition
                // from <50 MB to >=50 MB, so the user doesn't see a
                // toast every 60s once they're over.
                let mut last_was_oversized = false;
                loop {
                    tokio::select! {
                        biased;
                        _ = cancel.cancelled() => break,
                        _ = tick.tick() => {}
                        _ = notify.notified() => {}
                    }
                    if store.pending_wal_entries() == 0 {
                        continue;
                    }
                    if let Err(e) = store.checkpoint(&doc.doc()) {
                        error!("checkpoint failed: {e}");
                        continue;
                    }
                    let stats = store.storage_stats();
                    let oversized = stats.snapshot_bytes > SNAPSHOT_WARNING_BYTES;
                    if oversized && !last_was_oversized {
                        if let Some(events) = &events {
                            events.p2p_warning(&format!(
                                "Sync snapshot is {} MB — consider rotating the secret to start fresh.",
                                stats.snapshot_bytes / 1_000_000
                            ));
                        }
                    }
                    last_was_oversized = oversized;
                }
            }
        }));

        info!("sync engine started: endpoint_id={endpoint_id}");

        Ok(Arc::new(Self {
            doc,
            store,
            transport,
            bridge,
            endpoint_id,
            cancel,
            _local_sub: local_sub,
            _local_pump: local_pump,
            _inbox_task: inbox_task,
            _checkpoint_task: checkpoint_task,
        }))
    }

    pub fn endpoint_id(&self) -> EndpointId {
        self.endpoint_id
    }

    pub fn doc(&self) -> Arc<SyncDoc> {
        self.doc.clone()
    }

    pub fn store(&self) -> Arc<SyncStore> {
        self.store.clone()
    }

    pub fn transport(&self) -> Arc<Transport> {
        self.transport.clone()
    }

    pub fn bridge(&self) -> Arc<Bridge> {
        self.bridge.clone()
    }

    /// Force a checkpoint immediately. Called on graceful shutdown.
    pub fn checkpoint_now(&self) -> Result<()> {
        self.store.checkpoint(&self.doc.doc())
    }

    /// Cancel all background tasks and force a final checkpoint. Returns
    /// the held Transport so the caller can `transport.shutdown().await`
    /// — Transport::shutdown takes `self`, which doesn't compose with
    /// the Arc<Transport> lifetime here.
    pub async fn shutdown(&self) -> Result<()> {
        self.cancel.cancel();
        if let Err(e) = self.checkpoint_now() {
            warn!("final checkpoint failed: {e}");
        }
        Ok(())
    }
}

async fn handle_inbound(
    doc: &SyncDoc,
    transport: &Transport,
    pool: Option<&sqlx::SqlitePool>,
    client: Option<&Arc<crate::client::BrightspaceClient>>,
    from: &str,
    msg: WireMsg,
) {
    match msg {
        WireMsg::Update { bytes } | WireMsg::Snapshot { bytes } => {
            if let Err(e) = doc.doc().import(&bytes) {
                warn!("inbound import from {from} failed: {e}");
            }
        }
        WireMsg::StateRequest { vv: their_vv_bytes } => {
            let their_vv = match VersionVector::decode(&their_vv_bytes) {
                Ok(v) => v,
                Err(e) => {
                    warn!("malformed state vector from {from}: {e}");
                    return;
                }
            };
            let our_vv_bytes = doc.doc().oplog_vv().encode();
            let bytes = match doc.doc().export(ExportMode::updates(&their_vv)) {
                Ok(b) => b,
                Err(e) => {
                    warn!("export updates_since failed: {e}");
                    return;
                }
            };
            let response = WireMsg::StateResponse { vv: our_vv_bytes, bytes };
            if let Err(e) = transport.broadcast(response).await {
                warn!("state response broadcast to {from} failed: {e}");
            }
        }
        WireMsg::StateResponse { bytes, .. } => {
            if let Err(e) = doc.doc().import(&bytes) {
                warn!("state response import from {from} failed: {e}");
            }
        }
        WireMsg::PairingRequest { nonce } => {
            // Seed-side: gate on the nonce table. If the joiner is
            // legitimate (first use of this QR), record the nonce and
            // reply with a full snapshot. If the nonce is missing
            // (test wiring with `Bridge::new`), skip the gate but
            // still reply — that lets the integration test exercise
            // the snapshot path without bringing up a real DB.
            if let Some(pool) = pool {
                if let Err(e) = crate::p2p::pairing::consume_nonce(pool, &nonce).await {
                    warn!("rejecting pairing request from {from}: {e}");
                    return;
                }
            }
            let bytes = match doc.doc().export(loro::ExportMode::Snapshot) {
                Ok(b) => b,
                Err(e) => {
                    warn!("snapshot export for {from} failed: {e}");
                    return;
                }
            };
            if let Err(e) = transport.broadcast(WireMsg::Snapshot { bytes }).await {
                warn!("pairing snapshot broadcast to {from} failed: {e}");
                return;
            }
            // One-shot credential bootstrap so the joining device (often
            // a fresh iOS install with no way to drive Brightspace
            // sign-in) can skip first-time login. Sent after the
            // snapshot so the joiner already has its overlay data
            // imported by the time the credentials land. No-op if the
            // seed itself isn't authenticated, or if we lack a pool
            // (test wiring).
            if let Some(pool) = pool {
                match fetch_bootstrap_credentials(pool).await {
                    Ok(Some(creds)) => {
                        if let Err(e) = transport.broadcast(creds).await {
                            warn!("bootstrap credentials broadcast to {from} failed: {e}");
                        }
                    }
                    Ok(None) => {
                        // Seed not authenticated — silently skip. Joiner
                        // will fall back to the manual sign-in flow.
                    }
                    Err(e) => warn!("read bootstrap credentials failed: {e}"),
                }
            }
        }
        WireMsg::BootstrapCredentials { host, cookie, uid, user_id } => {
            // Joiner-side: persist the seed's session if (and only if)
            // we don't already have one. The "no clobber" check makes
            // re-pairing safe and prevents a stale paired device from
            // overwriting a freshly-rotated cookie on this one.
            let Some(client) = client else {
                warn!("ignoring BootstrapCredentials: no client wired");
                return;
            };
            let Some(pool) = pool else {
                warn!("ignoring BootstrapCredentials: no pool wired");
                return;
            };
            if client.is_configured() {
                tracing::debug!(
                    "ignoring BootstrapCredentials from {from}: already authenticated"
                );
                return;
            }
            match client
                .store_credentials(
                    pool,
                    &host,
                    &cookie,
                    uid.as_deref(),
                    user_id.as_deref(),
                )
                .await
            {
                Ok(()) => {
                    tracing::info!(
                        "adopted Brightspace credentials from paired device ({})",
                        from
                    );
                    // Same app-event the desktop login flow emits on
                    // success; the React layer already listens for it
                    // and refreshes auth status / kicks off a sync.
                    let _ = client.emit_auth_captured(&host);
                }
                Err(e) => warn!("store_credentials from {from} failed: {e}"),
            }
        }
    }
}

/// Read the seed's current Brightspace credentials out of
/// `user_preferences` for a `BootstrapCredentials` push. Returns
/// `Ok(None)` if the seed isn't currently authenticated, so the seed
/// can quietly skip the push for that joiner.
async fn fetch_bootstrap_credentials(
    pool: &sqlx::SqlitePool,
) -> Result<Option<WireMsg>> {
    let row: Option<(
        Option<String>,
        Option<String>,
        Option<String>,
        Option<String>,
    )> = sqlx::query_as(
        "SELECT brightspace_host, brightspace_cookie, brightspace_uid, brightspace_user_id \
         FROM user_preferences LIMIT 1",
    )
    .fetch_optional(pool)
    .await?;
    let Some((Some(host), Some(cookie), uid, user_id)) = row else {
        return Ok(None);
    };
    if host.trim().is_empty() || cookie.trim().is_empty() {
        return Ok(None);
    }
    Ok(Some(WireMsg::BootstrapCredentials {
        host,
        cookie,
        uid,
        user_id,
    }))
}

/// Read the iroh node secret + shared sync_doc_secret, generating
/// and persisting either if missing.
///
/// On-disk format:
///   - `iroh_node_secret`: base64 of the 32-byte ed25519 secret bytes
///   - `sync_doc_secret`:  hex of the 32 raw bytes (matches the QR
///                          payload format from T-012 / design.md §6)
///
/// Storage: `crate::p2p::secrets` reads the OS keychain first and
/// falls back to the SQLite `app_state` table on systems without
/// keychain support (T-021). Existing pre-T-021 installs are
/// migrated transparently — `migrate_to_keychain` runs
/// unconditionally before the first load so a SQLite-only secret
/// moves into the keychain on the next start.
///
/// `sync_doc_secret` is wrapped in `Zeroizing` so the raw 32 bytes
/// get scrubbed from RAM on drop.
async fn load_or_init_secrets(
    pool: &sqlx::SqlitePool,
) -> Result<(SecretKey, Zeroizing<Vec<u8>>)> {
    use crate::p2p::secrets::{self, SecretKind};
    secrets::migrate_to_keychain(pool, SecretKind::IrohNodeSecret).await?;
    secrets::migrate_to_keychain(pool, SecretKind::SyncDocSecret).await?;

    let node_secret = match secrets::load(pool, SecretKind::IrohNodeSecret).await? {
        Some(s) => {
            let raw = B64
                .decode(s.as_bytes())
                .map_err(|e| AppError::Other(format!("decode iroh_node_secret: {e}")))?;
            let arr: [u8; 32] = raw
                .as_slice()
                .try_into()
                .map_err(|_| AppError::Other("iroh_node_secret length != 32".into()))?;
            SecretKey::from_bytes(&arr)
        }
        None => {
            let key = SecretKey::generate();
            let encoded = B64.encode(key.to_bytes());
            secrets::store(pool, SecretKind::IrohNodeSecret, &encoded).await?;
            key
        }
    };

    let doc_secret = match secrets::load(pool, SecretKind::SyncDocSecret).await? {
        Some(s) => {
            let raw = hex::decode(&s)
                .map_err(|e| AppError::Other(format!("decode sync_doc_secret: {e}")))?;
            if raw.len() != 32 {
                return Err(AppError::Other("sync_doc_secret length != 32".into()));
            }
            Zeroizing::new(raw)
        }
        None => {
            let mut buf = vec![0u8; 32];
            rand::thread_rng().fill_bytes(&mut buf);
            let encoded = hex::encode(&buf);
            secrets::store(pool, SecretKind::SyncDocSecret, &encoded).await?;
            Zeroizing::new(buf)
        }
    };

    Ok((node_secret, doc_secret))
}

/// Generic key/value read on `app_state`. Public so the pairing-related
/// commands (and T-022's storage stats) can share one well-known
/// helper rather than each rolling its own SELECT.
pub async fn get_app_state(pool: &sqlx::SqlitePool, key: &str) -> Result<Option<String>> {
    let row: Option<(Option<String>,)> =
        sqlx::query_as("SELECT value FROM app_state WHERE key = ?")
            .bind(key)
            .fetch_optional(pool)
            .await?;
    Ok(row.and_then(|(v,)| v))
}

pub async fn set_app_state(pool: &sqlx::SqlitePool, key: &str, value: &str) -> Result<()> {
    sqlx::query(
        "INSERT INTO app_state (key, value, updated_at) VALUES (?, ?, CURRENT_TIMESTAMP) \
         ON CONFLICT(key) DO UPDATE SET value = excluded.value, updated_at = CURRENT_TIMESTAMP",
    )
    .bind(key)
    .bind(value)
    .execute(pool)
    .await?;
    Ok(())
}

