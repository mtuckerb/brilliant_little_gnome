// SyncEngine — top-level coordinator for P2P sync (design.md §3, ticket T-008).
//
// Owns the LoroDoc, the SyncStore, the Transport, and the Bridge. On
// `start(state)` it:
//   1. loads (or generates + persists) the iroh node secret and the
//      shared sync_doc_secret from the `app_state` KV table
//   2. opens the on-disk SyncStore (snapshot + WAL) and hydrates a
//      LoroDoc from it
//   3. brings up the Transport (iroh endpoint + gossip topic)
//   4. wires up three background tasks behind the same CancellationToken:
//        a. local-update pump — every Loro commit fires the doc's
//           `subscribe_local_update` callback; the bytes are appended to
//           the WAL and broadcast on gossip as `WireMsg::Update`
//        b. inbox handler   — drains `Transport::subscribe()`, importing
//           inbound `Update` / `Snapshot` / `StateResponse` payloads and
//           replying to `StateRequest` with the missing-since-vv bytes
//        c. checkpoint scheduler — fires every `CHECKPOINT_INTERVAL` and
//           also on the local-update pump's notification when WAL entries
//           cross `CHECKPOINT_WAL_THRESHOLD`
//
// The local-update callback is the natural echo-storm guard for the
// broadcast path: Loro fires it only for updates generated by THIS
// doc's commits (not for `import()`), so remote messages can't bounce
// back out as broadcasts. The bridge's apply_remote → SQLite path
// (T-010) needs its own guard via the `Origin` marker.

#![allow(dead_code)]

