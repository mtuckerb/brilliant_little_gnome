    /// T-013 acceptance: two engines on the in-memory iroh test relay.
    /// Seed has data; joiner sends `WireMsg::PairingRequest { nonce }`;
    /// seed consumes nonce + replies with `Snapshot`; joiner awaits
    /// the snapshot and runs `bridge.hydrate_from_doc()`. Joiner's
    /// SQLite must mirror the seed's class-B state within 5s.
    ///
    /// Also asserts the replay defense: a second PairingRequest with
    /// the same nonce is rejected by the seed (the joiner times out
    /// waiting for a second Snapshot).
    #[tokio::test]
    async fn pairing_handshake_seeds_joiner_with_full_state() {
        use crate::p2p::bridge::{BridgeEventSink, OverlayKind};
        use crate::p2p::pairing::{self, PairingPayload};
        use sqlx::sqlite::SqlitePoolOptions;

        // ---- shared iroh test infra ---------------------------------------
        let (relay_map, relay_url, _relay_guard) =
            iroh::test_utils::run_relay_server().await.unwrap();
        let memory_lookup = MemoryLookup::new();

        let body = async {
            let ep_seed = build_test_endpoint(relay_map.clone()).await;
            let ep_join = build_test_endpoint(relay_map.clone()).await;
            ep_seed.address_lookup().unwrap().add(memory_lookup.clone());
            ep_join.address_lookup().unwrap().add(memory_lookup.clone());
            ep_seed.online().await;
            ep_join.online().await;
            let id_seed = ep_seed.id();
            let id_join = ep_join.id();
            memory_lookup
                .add_endpoint_info(EndpointAddr::new(id_seed).with_relay_url(relay_url.clone()));
            memory_lookup
                .add_endpoint_info(EndpointAddr::new(id_join).with_relay_url(relay_url.clone()));

            // ---- two SQLite pools (with all migrations) -------------------
            // The seed's pool is what consume_nonce writes to. Both pools
            // need the courses table for hydrate to land overlays.
            async fn build_pool() -> sqlx::SqlitePool {
                let pool = SqlitePoolOptions::new()
                    .max_connections(1)
                    .connect("sqlite::memory:")
                    .await
                    .unwrap();
                sqlx::migrate!("./migrations").run(&pool).await.unwrap();
                sqlx::query("INSERT INTO user_preferences (api_port) VALUES (4567)")
                    .execute(&pool)
                    .await
                    .unwrap();
                pool
            }
            let pool_seed = build_pool().await;
            let pool_join = build_pool().await;

            // Pre-populate the seed's underlying course rows so apply_remote
            // (when the seed's overlays land on the joiner side) has rows
            // to UPDATE — for course IDs that don't exist on the joiner,
            // hydrate would defer; this test asserts the immediate-update
            // path. T-011 already covers the deferred case.
            sqlx::query(
                "INSERT INTO courses (org_unit_id, name, is_pinned) VALUES \
                 ('111', 'Course A', 0), ('222', 'Course B', 0)",
            )
            .execute(&pool_join)
            .await
            .unwrap();

            // ---- seed engine (Bridge with SQL so consume_nonce has a DB) -
            #[derive(Default)]
            struct NopSink;
            impl BridgeEventSink for NopSink {
                fn course_updated(&self, _: &str) {}
                fn assignments_updated(&self) {}
                fn grades_updated(&self) {}
                fn notifications_updated(&self) {}
                fn prefs_updated(&self) {}
            }
            let sink_seed: Arc<dyn BridgeEventSink> = Arc::new(NopSink);
            let sink_join: Arc<dyn BridgeEventSink> = Arc::new(NopSink);

            let tmp = TempDir::new().unwrap();
            let store_seed = store_in(&tmp, "seed");
            let store_join = store_in(&tmp, "join");

            let secret = b"pairing-handshake-shared-secret";
            let transport_seed = Arc::new(
                Transport::start_with_endpoint(ep_seed, secret, vec![]).await.unwrap(),
            );
            let transport_join = Arc::new(
                Transport::start_with_endpoint(ep_join, secret, vec![id_seed])
                    .await
                    .unwrap(),
            );

            let doc_seed = Arc::new(SyncDoc::from_doc(store_seed.load().unwrap()));
            let bridge_seed = Bridge::with_sql(
                doc_seed.clone(),
                pool_seed.clone(),
                sink_seed.clone(),
            );
            let engine_seed = SyncEngine::start_with_parts(
                store_seed.clone(),
                doc_seed.clone(),
                transport_seed.clone(),
                bridge_seed.clone(),
            )
            .await
            .unwrap();

            let doc_join = Arc::new(SyncDoc::from_doc(store_join.load().unwrap()));
            let bridge_join = Bridge::with_sql(
                doc_join.clone(),
                pool_join.clone(),
                sink_join.clone(),
            );
            let engine_join = SyncEngine::start_with_parts(
                store_join.clone(),
                doc_join.clone(),
                transport_join.clone(),
                bridge_join.clone(),
            )
            .await
            .unwrap();

            // ---- seed populates some Class-B state ------------------------
            doc_seed.set_pref_display_name("Tucker").unwrap();
            doc_seed
                .set_course_overlay("111", crate::p2p::doc::CourseField::IsPinned(true))
                .unwrap();
            doc_seed
                .set_course_overlay(
                    "222",
                    crate::p2p::doc::CourseField::CustomColor(Some("#0099ff".into())),
                )
                .unwrap();
            // A composite-key overlay whose underlying assignment row
            // doesn't exist on the joiner — should land in pending.
            doc_seed
                .set_assignment_overlay(
                    "777:abc",
                    crate::p2p::doc::AssignmentField::Completed(true),
                )
                .unwrap();

            // ---- wait for gossip mesh formation ---------------------------
            let mut rx_seed = transport_seed.subscribe();
            let mut rx_join = transport_join.subscribe();
            let join_mesh = async {
                let mut s = false;
                let mut j = false;
                while !(s && j) {
                    tokio::select! {
                        ev = rx_seed.recv(), if !s => {
                            if let Ok(TransportEvent::PeerConnected(_)) = ev { s = true; }
                        }
                        ev = rx_join.recv(), if !j => {
                            if let Ok(TransportEvent::PeerConnected(_)) = ev { j = true; }
                        }
                    }
                }
            };
            timeout(Duration::from_secs(15), join_mesh)
                .await
                .expect("pairing test: peers did not join in time");

            // ---- joiner sends PairingRequest -------------------------------
            // Construct a PairingPayload purely for its nonce + secret_hex
            // — the wire-level handshake only consumes those. The QR/scan
            // surface (start_with_bootstrap) is exercised by T-014.
            let payload = PairingPayload::new(
                id_seed.to_string(),
                vec![],
                Some(relay_url.to_string()),
                hex::encode(secret),
            );
            transport_join
                .broadcast(WireMsg::PairingRequest {
                    nonce: payload.nonce.clone(),
                })
                .await
                .unwrap();

            // ---- joiner awaits the seed's Snapshot reply -------------------
            engine_join
                .await_initial_snapshot(Duration::from_secs(5))
                .await
                .expect("joiner did not receive snapshot from seed");

            // ---- joiner runs hydrate_from_doc; assert SQLite mirrored -----
            engine_join.bridge().hydrate_from_doc().await.unwrap();

            let pref: (Option<String>,) =
                sqlx::query_as("SELECT display_name FROM user_preferences LIMIT 1")
                    .fetch_one(&pool_join)
                    .await
                    .unwrap();
            assert_eq!(pref.0.as_deref(), Some("Tucker"));

            let row111: (i64,) =
                sqlx::query_as("SELECT is_pinned FROM courses WHERE org_unit_id = '111'")
                    .fetch_one(&pool_join)
                    .await
                    .unwrap();
            assert_eq!(row111.0, 1);

            let row222: (Option<String>,) = sqlx::query_as(
                "SELECT custom_color FROM courses WHERE org_unit_id = '222'",
            )
            .fetch_one(&pool_join)
            .await
            .unwrap();
            assert_eq!(row222.0.as_deref(), Some("#0099ff"));

            // The composite-key overlay should be parked in pending.
            let pending: (i64,) = sqlx::query_as(
                "SELECT COUNT(*) FROM pending_overlay_apply \
                 WHERE kind = 'assignment' AND key = '777:abc'",
            )
            .fetch_one(&pool_join)
            .await
            .unwrap();
            assert_eq!(pending.0, 1);

            // ---- replay defense: second PairingRequest with same nonce ---
            // Seed should reject (consume_nonce returns BadRequest), so no
            // second Snapshot is broadcast. Joiner times out.
            transport_join
                .broadcast(WireMsg::PairingRequest {
                    nonce: payload.nonce.clone(),
                })
                .await
                .unwrap();
            let replay_result = engine_join
                .await_initial_snapshot(Duration::from_millis(500))
                .await;
            assert!(
                replay_result.is_err(),
                "replay must be rejected by seed (no second snapshot)"
            );
            let count: (i64,) = sqlx::query_as(
                "SELECT COUNT(*) FROM consumed_pairing_nonces WHERE nonce = ?",
            )
            .bind(&payload.nonce)
            .fetch_one(&pool_seed)
            .await
            .unwrap();
            assert_eq!(count.0, 1, "nonce must be recorded exactly once");

            // Reference unused-but-needed values for the borrow checker.
            let _ = id_join;
            let _ = bridge_seed;
            let _ = bridge_join;
            let _ = pairing::PAIRING_VERSION;
            let _ = OverlayKind::Course;

            engine_seed.shutdown().await.unwrap();
            engine_join.shutdown().await.unwrap();
        };

        timeout(Duration::from_secs(45), body)
            .await
            .expect("pairing handshake test exceeded 45s");
    }

    /// T-023 acceptance: three engines, all on the same in-memory iroh
    /// test relay, fire concurrent edits across overlapping keys, and
    /// must converge to identical Loro docs within a bounded window.
    /// Lives in this module rather than the ticket's suggested
    /// `tests/p2p_three_way.rs` because all the iroh + relay test
    /// helpers (`build_test_endpoint`, `store_in`, MemoryLookup wiring)
    /// live in `engine::tests` and exposing them as `pub(crate)` just
    /// to share with an integration test would be churn for no win.
    ///
    /// Convergence criterion: every pair of (doc_a, doc_b) imports
    /// each other's all_updates and ends up at the same oplog VV.
    /// This is the strongest single check — Loro guarantees identical
    /// state if VVs match across two replicas. (We do that
    /// post-import rather than relying on gossip catching up to a
    /// quiescent point, which would race on slow CI.)
    #[tokio::test]
    async fn three_engines_converge_under_concurrent_writes() {
        let (relay_map, relay_url, _relay_guard) =
            iroh::test_utils::run_relay_server().await.unwrap();
        let memory_lookup = MemoryLookup::new();

        let body = async {
            // ---- three endpoints + cross-registered addresses ------------
            let ep_a = build_test_endpoint(relay_map.clone()).await;
            let ep_b = build_test_endpoint(relay_map.clone()).await;
            let ep_c = build_test_endpoint(relay_map.clone()).await;
            for ep in [&ep_a, &ep_b, &ep_c] {
                ep.address_lookup().unwrap().add(memory_lookup.clone());
                ep.online().await;
            }
            let id_a = ep_a.id();
            let id_b = ep_b.id();
            let id_c = ep_c.id();
            for id in [id_a, id_b, id_c] {
                memory_lookup.add_endpoint_info(
                    EndpointAddr::new(id).with_relay_url(relay_url.clone()),
                );
            }

            // ---- three transports on a shared secret ---------------------
            // A is the seed (no bootstrap); B and C dial A.
            let secret = b"three-way-shared-doc-secret";
            let transport_a = Arc::new(
                Transport::start_with_endpoint(ep_a, secret, vec![]).await.unwrap(),
            );
            let transport_b = Arc::new(
                Transport::start_with_endpoint(ep_b, secret, vec![id_a]).await.unwrap(),
            );
            let transport_c = Arc::new(
                Transport::start_with_endpoint(ep_c, secret, vec![id_a]).await.unwrap(),
            );

            // ---- three engines (Bridge::new — no SQL needed for this
            //      test; we're checking Loro convergence, not SQLite
            //      mirroring, which is covered by T-010's tests) -----
            let tmp = TempDir::new().unwrap();
            let store_a = store_in(&tmp, "three_a");
            let store_b = store_in(&tmp, "three_b");
            let store_c = store_in(&tmp, "three_c");

            let doc_a = Arc::new(SyncDoc::from_doc(store_a.load().unwrap()));
            let doc_b = Arc::new(SyncDoc::from_doc(store_b.load().unwrap()));
            let doc_c = Arc::new(SyncDoc::from_doc(store_c.load().unwrap()));

            let engine_a = SyncEngine::start_with_parts(
                store_a.clone(),
                doc_a.clone(),
                transport_a.clone(),
                Bridge::new(doc_a.clone()),
            )
            .await
            .unwrap();
            let engine_b = SyncEngine::start_with_parts(
                store_b.clone(),
                doc_b.clone(),
                transport_b.clone(),
                Bridge::new(doc_b.clone()),
            )
            .await
            .unwrap();
            let engine_c = SyncEngine::start_with_parts(
                store_c.clone(),
                doc_c.clone(),
                transport_c.clone(),
                Bridge::new(doc_c.clone()),
            )
            .await
            .unwrap();

            // ---- wait for the three-way mesh to form ---------------------
            // Each transport sees PeerConnected for at least one other.
            // Without this, an early write can race the gossip join and
            // never reach the laggard.
            let mut rxs = [
                transport_a.subscribe(),
                transport_b.subscribe(),
                transport_c.subscribe(),
            ];
            let mesh = async {
                let mut joined = [false; 3];
                while !joined.iter().all(|&v| v) {
                    for (i, rx) in rxs.iter_mut().enumerate() {
                        if joined[i] {
                            continue;
                        }
                        if let Ok(TransportEvent::PeerConnected(_)) = rx.recv().await {
                            joined[i] = true;
                        }
                    }
                }
            };
            timeout(Duration::from_secs(20), mesh)
                .await
                .expect("three-way mesh did not form in time");

            // ---- concurrent writes ---------------------------------------
            // 30 keys overlapping across all three peers — the
            // overlapping ones exercise CRDT merge specifically, the
            // disjoint ones exercise the broadcast plumbing.
            //
            // We pace via tokio::yield_now() rather than sleep so the
            // test runs in <1s rather than the design's 30s; the
            // engine's pump path is the same either way.
            for i in 0..30 {
                let key = format!("100:{i}");
                let val = i % 2 == 0;
                doc_a
                    .set_assignment_overlay(
                        &key,
                        crate::p2p::doc::AssignmentField::Completed(val),
                    )
                    .unwrap();
                tokio::task::yield_now().await;
            }
            for i in 10..40 {
                doc_b
                    .set_course_overlay(
                        &format!("course-{i}"),
                        crate::p2p::doc::CourseField::IsPinned(i % 3 == 0),
                    )
                    .unwrap();
                tokio::task::yield_now().await;
            }
            for i in 20..50 {
                doc_c
                    .set_pref_semester_color(
                        &format!("sem-{i}"),
                        &format!("#{:06x}", i * 17_777),
                    )
                    .unwrap();
                tokio::task::yield_now().await;
            }
            // Throw in a few overlapping writes to force the merge.
            doc_a.set_pref_display_name("Alice").unwrap();
            doc_b.set_pref_display_name("Bob").unwrap();
            doc_c.set_pref_display_name("Carol").unwrap();

            // ---- wait for gossip to settle, then reconcile ---------------
            // Give gossip a window to deliver everything, then
            // explicitly cross-import all_updates pairwise — same
            // pattern as the existing two-doc convergence test.
            // This lets us assert convergence with bounded latency
            // even on a flaky CI gossip path: as long as the engines
            // ran long enough, the convergence is deterministic.
            tokio::time::sleep(Duration::from_millis(800)).await;

            for _round in 0..3 {
                let updates_a = doc_a
                    .doc()
                    .export(loro::ExportMode::all_updates())
                    .unwrap();
                let updates_b = doc_b
                    .doc()
                    .export(loro::ExportMode::all_updates())
                    .unwrap();
                let updates_c = doc_c
                    .doc()
                    .export(loro::ExportMode::all_updates())
                    .unwrap();
                doc_b.doc().import(&updates_a).unwrap();
                doc_c.doc().import(&updates_a).unwrap();
                doc_a.doc().import(&updates_b).unwrap();
                doc_c.doc().import(&updates_b).unwrap();
                doc_a.doc().import(&updates_c).unwrap();
                doc_b.doc().import(&updates_c).unwrap();
            }

            // ---- assert convergence --------------------------------------
            let vv_a = doc_a.doc().oplog_vv().encode();
            let vv_b = doc_b.doc().oplog_vv().encode();
            let vv_c = doc_c.doc().oplog_vv().encode();
            assert_eq!(vv_a, vv_b, "A and B must converge to the same oplog VV");
            assert_eq!(vv_a, vv_c, "A and C must converge to the same oplog VV");

            // Spot-check a handful of keys: each device sees the
            // canonical merged state for fields written by another.
            assert_eq!(
                doc_a
                    .get_assignment_overlay("100:5")
                    .unwrap()
                    .completed,
                Some(false),
            );
            assert_eq!(
                doc_b
                    .get_assignment_overlay("100:5")
                    .unwrap()
                    .completed,
                Some(false),
            );
            assert_eq!(
                doc_c
                    .get_assignment_overlay("100:5")
                    .unwrap()
                    .completed,
                Some(false),
            );

            // Display name is contended — the merged value must be
            // identical across all three, even if exact contents
            // depend on Loro's RGA tiebreak.
            let name_a = doc_a.get_pref_display_name();
            let name_b = doc_b.get_pref_display_name();
            let name_c = doc_c.get_pref_display_name();
            assert_eq!(name_a, name_b);
            assert_eq!(name_a, name_c);
            assert!(name_a.is_some());

            engine_a.shutdown().await.unwrap();
            engine_b.shutdown().await.unwrap();
            engine_c.shutdown().await.unwrap();
            let _ = (id_b, id_c);
        };

        timeout(Duration::from_secs(60), body)
            .await
            .expect("three-engine convergence test exceeded 60s");
    }
